"""Generate the M8 guide's Faded Polaroid song spec, and the patch-card specs that share its
parts, from the parts model and the settings. Run from the repo root:

    python3 tools/m8_faded_polaroid.py site/guides/m8

Sources (DRAFT, 2026-10-29): tools/songs/fp.py (every phrase, chain and song row; its sheet is
docs/songs/faded-polaroid-parts.md) and tools/songs/instruments.py (every instrument, table,
groove and the mix; docs/songs/faded-polaroid-instruments.md). Edit those, not the JSON.
What this script adds: the workbench song rows of steps 2 to 9 (the parts sheet, section 5),
the silence chain FE in the finished song's empty cells, the harmony list the panels draw,
and the paraphonic chord shapes the demo uses to draw and sound instrument 10's chords.
"""
import json, sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent / "songs"))
import fp  # noqa: E402
from instruments import SONGS  # noqa: E402
from spec import phrases, chains, instruments, song_rows, nostep, pick  # noqa: E402

OUT = Path(sys.argv[1])
S = SONGS["faded-polaroid"]

# Instrument 10's COLOR shapes, as the parts sheet voices them (section 3): COLOR 80 plus the
# COL value lands on these. From the Braids source and the chat, not his ears, except 34.
SHAPES = [
    {"color": "34", "iv": ["00", "03", "07", "0A"], "name": "minor 7"},
    {"color": "A4", "iv": ["00", "04", "07", "0E"], "name": "major add 9"},
    {"color": "C4", "iv": ["00", "04", "07", "0B"], "name": "major 7"},
    {"color": "D4", "iv": ["00", "05", "07", "0C"], "name": "sus4 + octave"},
]

# The workbench (parts sheet, section 5): (row, track, chain, from step, until step).
# Rows 00-02 at step 9 get FE on the tracks they don't use, so the song plays the three rows
# in step on the M8 (an empty cell would send a track back to its first chain).
W = [("00", 3, "03", 2, 9), ("00", 2, "02", 3, 4), ("00", 1, "01", 4, 9), ("00", 2, "21", 5, 7),
     ("00", 5, "05", 5, 9), ("00", 6, "06", 5, 9), ("00", 4, "04", 6, 6), ("00", 4, "42", 7, 9),
     ("00", 2, "22", 8, 9),
     ("01", 1, "12", 8, 9), ("01", 2, "24", 8, 9), ("01", 3, "31", 8, 9), ("01", 4, "41", 8, 9),
     ("01", 5, "51", 8, 9), ("01", 6, "06", 8, 9),
     ("00", 7, "FE", 9, 9), ("01", 7, "FE", 9, 9), ("02", 7, "07", 9, 9)] + \
    [("02", t, "FE", 9, 9) for t in range(1, 7)]

FE_CHAIN = {"FE": (["FD"] + ["FE"] * 7, 9)}


def harm(bar, chord, roman, bass, upper, move, step, until=None, hold=None):
    h = {"bar": bar, "chord": chord, "roman": roman, "bass": bass, "upper": upper, "move": move, "step": step}
    if hold:
        h["hold"] = hold
    if until is not None:
        h["until"] = until
    return h


A = [("Dmaj9", "I", "D", "F♯ A C♯ E", "home; the top voice is the ninth, E"),
     ("Aadd9", "V", "A", "A C♯ E B", "the bass falls a fourth; the top is the ninth again, B"),
     ("Bm9", "vi", "B", "D F♯ A C♯", "the bass steps up; the top is the ninth, C♯"),
     ("Gmaj9", "IV", "G", "B D F♯ A", "the bass falls a third; back to D")]
B = [(9, 2, "Em9", "ii", "E", "G B D F♯", "two bars a chord now; the bass falls to the song's lowest note"),
     (11, 2, "Gmaj9", "IV", "G", "B D F♯ A", "the bass climbs a third; the top A arrives and stays"),
     (13, 2, "Gm9", "iv", "G", "B♭ D F A", "borrowed from D minor: B falls to B♭, F♯ to F, under a held A"),
     (15, 1, "Asus4", "V sus", "A", "A D E A", "B♭ falls to A; the bass steps up"),
     (16, 1, "Aadd9", "V", "A", "A C♯ E B", "D falls to C♯ inside the chord; home to Dmaj9")]
harmony = [harm(i + 1, *A[i], step=2, until=9) for i in range(4)]
harmony += [harm(i + 5, *A[i], step=8, until=9) for i in range(4)]
harmony += [harm(b, c, r, bs, u, m, step=8, until=9, hold=h) for b, h, c, r, bs, u, m in B]
harmony += [harm(17 + 2 * i, A[i][0], A[i][1], "none", "the memory, an octave down", "two bars a chord: the loop at half speed",
                 step=9, until=9, hold=2) for i in range(4)]

tracks = [
    {"n": 1, "name": "Arp", "step": 4}, {"n": 2, "name": "Bass", "step": 3}, {"n": 3, "name": "Chords", "step": 2},
    {"n": 4, "name": "Lead", "step": 6}, {"n": 5, "name": "Kick + snare", "step": 5}, {"n": 6, "name": "Hats", "step": 5},
    {"n": 7, "name": "Faded loop", "step": 9}, {"n": 8, "name": "Freeze", "step": 10},
]

PH = phrases(fp.P)
PH["FD"]["rows"]["0"]["step"] = 9  # the silence chain FE is first needed in step 9's workbench rows
CH = chains(fp.C, fp.CSTEP, FE_CHAIN)
INST = instruments(S["instruments"], {"10": {"shapes": SHAPES}})

spec = {
    "title": "Faded Polaroid", "tempo": 90, "key": "D major", "firmware": "6.6.3",
    "upperLabel": "chords",
    "notes": "DRAFT. Generated by tools/m8_faded_polaroid.py from tools/songs/fp.py and tools/songs/instruments.py; "
             "see docs/songs/faded-polaroid-parts.md and faded-polaroid-instruments.md. Every element carries the "
             "walkthrough step that introduces it (and `until`, the last step it belongs to).",
    "grooves": S["grooves"],
    "tracks": tracks,
    "song": song_rows(W, fp.SONG, range(2, 10), 10),
    "chains": CH, "phrases": PH, "instruments": INST, "tables": S["tables"], "harmony": harmony, "mix": S["mix"],
}
(OUT / "songs/faded-polaroid.json").write_text(json.dumps(spec, indent=1, ensure_ascii=False) + "\n")

# ---- patch cards that share the song's parts (every element on from the start)
lead = {
    "title": "Polaroid lead", "tempo": 90, "key": "D major", "firmware": "6.6.3", "upperLabel": "chords",
    "notes": "Faded Polaroid's hook (steps 6 and 7) over his chords, as a patch card. Generated by tools/m8_faded_polaroid.py.",
    "tracks": [{"n": 4, "name": "Lead"}, {"n": 3, "name": "Chords"}],
    "song": [{"row": "00", "chains": {"3": "03", "4": "04"}}],
    "chains": {"04": [{"ph": p} for p in ["40", "41", "42", "43"]], "03": [{"ph": p} for p in ["30", "31", "32", "33"]]},
    "phrases": nostep(pick(PH, ["40", "41", "42", "43", "30", "31", "32", "33"])),
    "instruments": nostep(pick(INST, ["04", "10"])),
    "tables": nostep(pick(S["tables"], ["04", "81"])),
    "harmony": nostep(harmony[:4]),
}
(OUT / "patches/polaroid-lead.json").write_text(json.dumps(lead, indent=1, ensure_ascii=False) + "\n")

memory = {
    "title": "The memory", "tempo": 90, "key": "D major", "firmware": "6.6.3",
    "notes": "Faded Polaroid's faded loop (step 9) as a patch card. Generated by tools/m8_faded_polaroid.py.",
    "tracks": [{"n": 7, "name": "Faded loop"}],
    "song": [{"row": "00", "chains": {"7": "07"}}, {"row": "01", "chains": {"7": "72"}}],
    "chains": nostep(pick(CH, ["07", "72"])),
    "phrases": nostep(pick(PH, ["70", "72", "FE"])),
    "instruments": nostep(pick(INST, ["09", "0A"])),
}
(OUT / "patches/faded-memory.json").write_text(json.dumps(memory, indent=1, ensure_ascii=False) + "\n")
print("ok", len(spec["song"]), "song entries")
